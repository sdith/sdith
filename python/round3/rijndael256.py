RCON = [0x01, 0x02, 0x04, 0x08, 0x10,
        0x20, 0x40, 0x80, 0x1b, 0x36,
        0x6c, 0xd8, 0xab, 0x4d]

NUM_COLUMNS = 8
NUM_ROUNDS = 14
BLOCK_SIZE = 32


def _xtime(a):
    """Multiply by x in GF(2^8) with AES reduction polynomial."""
    return ((a << 1) ^ (0x1b if a & 0x80 else 0)) & 0xFF


def _sub_bytes(state):
    for i in range(BLOCK_SIZE):
        state[i] = SBOX[state[i]]


def _shift_rows(state):
    row1 = [state[4 * i + 1] for i in range(NUM_COLUMNS)]
    for i in range(NUM_COLUMNS):
        state[4 * i + 1] = row1[(i + 1) % NUM_COLUMNS]

    row2 = [state[4 * i + 2] for i in range(NUM_COLUMNS)]
    for i in range(NUM_COLUMNS):
        state[4 * i + 2] = row2[(i + 3) % NUM_COLUMNS]

    row3 = [state[4 * i + 3] for i in range(NUM_COLUMNS)]
    for i in range(NUM_COLUMNS):
        state[4 * i + 3] = row3[(i + 4) % NUM_COLUMNS]


def _mix_columns(state):
    for col in range(NUM_COLUMNS):
        base = 4 * col
        s0, s1, s2, s3 = (state[base], state[base + 1],
                           state[base + 2], state[base + 3])
        state[base] = _xtime(s0) ^ _xtime(s1) ^ s1 ^ s2 ^ s3
        state[base + 1] = _xtime(s1) ^ _xtime(s2) ^ s2 ^ s3 ^ s0
        state[base + 2] = _xtime(s2) ^ _xtime(s3) ^ s3 ^ s0 ^ s1
        state[base + 3] = _xtime(s3) ^ _xtime(s0) ^ s0 ^ s1 ^ s2


def _add_round_key(state, round_key):
    for i in range(BLOCK_SIZE):
        state[i] ^= round_key[i]


def _key_schedule(key):
    """Expand 32-byte key into NUM_ROUNDS+1 round keys."""
    round_keys = [bytearray(BLOCK_SIZE)
                  for _ in range(NUM_ROUNDS + 1)]
    round_keys[0][:] = key

    for r in range(1, NUM_ROUNDS + 1):
        prev = round_keys[r - 1]
        cur = round_keys[r]
        for col in range(NUM_COLUMNS):
            if col == 0:
                cur[0] = prev[0] ^ SBOX[prev[29]] ^ RCON[r - 1]
                cur[1] = prev[1] ^ SBOX[prev[30]]
                cur[2] = prev[2] ^ SBOX[prev[31]]
                cur[3] = prev[3] ^ SBOX[prev[28]]
            elif col == 4:
                cur[16] = prev[16] ^ SBOX[cur[12]]
                cur[17] = prev[17] ^ SBOX[cur[13]]
                cur[18] = prev[18] ^ SBOX[cur[14]]
                cur[19] = prev[19] ^ SBOX[cur[15]]
            else:
                for i in range(4):
                    cur[col * 4 + i] = (prev[col * 4 + i]
                                        ^ cur[(col - 1) * 4 + i])

    return round_keys


def rijndael256_encrypt(key, plaintext):
    """Encrypt a single 32-byte block with a 32-byte key."""
    round_keys = _key_schedule(key)
    state = bytearray(plaintext)

    _add_round_key(state, round_keys[0])
    for r in range(1, NUM_ROUNDS):
        _sub_bytes(state)
        _shift_rows(state)
        _mix_columns(state)
        _add_round_key(state, round_keys[r])
    _sub_bytes(state)
    _shift_rows(state)
    _add_round_key(state, round_keys[NUM_ROUNDS])

    return bytes(state)
